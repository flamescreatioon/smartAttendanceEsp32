import { useMemo, useState } from 'react';
import { useMutation, useQuery } from '@tanstack/react-query';
import { BookOpen, Cpu, Database, KeyRound, RefreshCw, RadioTower, Save, Trash2, Users } from 'lucide-react';
import { formatDateTime } from '../utils/format.js';
import toast from 'react-hot-toast';
import Header from '../components/Header.jsx';
import StatusBadge from '../components/StatusBadge.jsx';
import { useAttendance } from '../hooks/useAttendance.js';
import {
  API_BASE_URL,
  getCourses,
  saveCourseRoster,
  SOCKET_URL,
} from '../services/api.js';
import { getSessionStatus, maskApiKey } from '../utils/format.js';

function buildInitialRosterForm() {
  return {
    courseCode: '',
    courseTitle: '',
    lecturerId: '',
    rosterCsv: 'matricNumber,firstName,lastName,department,email,phoneNumber',
  };
}

function parseRosterCsv(csvText) {
  const lines = csvText
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean);

  if (lines.length === 0) {
    return [];
  }

  const normalizedHeader = lines[0].toLowerCase().replace(/\s+/g, '');
  const hasHeader = normalizedHeader.includes('matricnumber');
  const dataLines = hasHeader ? lines.slice(1) : lines;

  return dataLines.map((line, index) => {
    const columns = line.split(',').map((value) => value.trim());

    if (columns.length < 6) {
      throw new Error(`Roster row ${index + 1} must contain 6 comma-separated values.`);
    }

    const [matricNumber, firstName, lastName, department, email, phoneNumber] = columns;

    return {
      matricNumber,
      firstName,
      lastName,
      department,
      email,
      phoneNumber,
    };
  });
}

export default function Settings({ auth, onLogout }) {
  const [rosterForm, setRosterForm] = useState(buildInitialRosterForm);
  const {
    session,
    deviceStatusQuery,
    socketConnected,
  } = useAttendance({ token: auth.token });

  const device = deviceStatusQuery.data?.device ?? session?.device ?? null;
  const coursesQuery = useQuery({
    queryKey: ['courses', auth.token],
    queryFn: () => getCourses(auth.token),
    enabled: Boolean(auth.token),
    staleTime: 30000,
  });

  const saveRosterMutation = useMutation({
    mutationFn: async () => {
      const students = parseRosterCsv(rosterForm.rosterCsv);

      return saveCourseRoster(
        rosterForm.courseCode.trim(),
        {
          courseTitle: rosterForm.courseTitle.trim(),
          lecturerId: rosterForm.lecturerId.trim(),
          students,
        },
        auth.token,
      );
    },
    onSuccess: (course) => {
      toast.success(`Roster saved for ${course.code}.`);
      coursesQuery.refetch();
    },
    onError: (error) => {
      toast.error(error.response?.data?.message ?? error.message ?? 'Unable to save the course roster.');
    },
  });

  function updateRosterForm(fieldName, value) {
    setRosterForm((currentForm) => ({
      ...currentForm,
      [fieldName]: value,
    }));
  }

  function loadCourseIntoForm(course) {
    updateRosterForm('courseCode', course.code || '');
    updateRosterForm('courseTitle', course.title || '');
    updateRosterForm('lecturerId', course.lecturerId || '');
    updateRosterForm(
      'rosterCsv',
      [
        'matricNumber,firstName,lastName,department,email,phoneNumber',
        ...(course.students ?? []).map((student) => (
          [
            student.matricNumber,
            student.firstName,
            student.lastName,
            student.department ?? '',
            student.email ?? '',
            student.phoneNumber ?? '',
          ].join(',')
        )),
      ].join('\n'),
    );
  }

  function handleSaveRoster(event) {
    event.preventDefault();
    saveRosterMutation.mutate();
  }

  const parsedRosterCount = useMemo(() => {
    try {
      return parseRosterCsv(rosterForm.rosterCsv).length;
    } catch {
      return 0;
    }
  }, [rosterForm.rosterCsv]);
  const apiBaseLabel = API_BASE_URL || `${window.location.origin} (same-origin proxy)`;
  const socketBaseLabel = SOCKET_URL || `${window.location.origin} (same-origin proxy)`;
  const attendanceUrlLabel = session?.attendanceUrl || 'Generated by the backend from PUBLIC_ATTENDANCE_URL';

  return (
    <main className="app-shell">
      <Header
        auth={auth}
        session={session}
        device={device}
        socketConnected={socketConnected}
        onLogout={onLogout}
      />

      <section className="page-section">
        <div className="page-section__heading">
          <div>
            <span className="eyebrow">Settings</span>
            <h2>Connection, access, and class rosters</h2>
            <p>
              Manage runtime targets and upload enrolled class lists so session reports can calculate absent students and attendance percentages.
            </p>
          </div>
        </div>
      </section>

      <section className="settings-grid">
        <article className="panel settings-card">
          <div className="panel-heading">
            <div>
              <span className="eyebrow">Backend targets</span>
              <h2>Runtime endpoints</h2>
            </div>
            <StatusBadge status={socketConnected ? 'ACTIVE' : 'OFFLINE'} />
          </div>

          <dl className="settings-list">
            <div>
              <dt><Database size={16} /> API base</dt>
              <dd>{apiBaseLabel}</dd>
            </div>
            <div>
              <dt><RadioTower size={16} /> Socket endpoint</dt>
              <dd>{socketBaseLabel}</dd>
            </div>
            <div>
              <dt><RefreshCw size={16} /> Attendance URL source</dt>
              <dd>{attendanceUrlLabel}</dd>
            </div>
          </dl>
        </article>

        <article className="panel settings-card">
          <div className="panel-heading">
            <div>
              <span className="eyebrow">Saved access</span>
              <h2>Operator credentials</h2>
            </div>
            <button
              type="button"
              className="button button--ghost"
              onClick={() => deviceStatusQuery.refetch()}
              disabled={deviceStatusQuery.isFetching}
            >
              <RefreshCw size={16} />
              <span>{deviceStatusQuery.isFetching ? 'Checking...' : 'Check device'}</span>
            </button>
          </div>

          <dl className="settings-list">
            <div>
              <dt><KeyRound size={16} /> Dashboard token</dt>
              <dd>{maskApiKey(auth.token)}</dd>
            </div>
            <div>
              <dt><Users size={16} /> Dashboard user</dt>
              <dd>{auth.operatorName || auth.email || 'Not available'}</dd>
            </div>
            <div>
              <dt><Database size={16} /> Device name</dt>
              <dd>{device?.name || auth.deviceName || 'Not available'}</dd>
            </div>
            <div>
              <dt><Cpu size={16} /> Device ID</dt>
              <dd>{device?.deviceId || auth.deviceId || 'Not available'}</dd>
            </div>
            <div>
              <dt><RadioTower size={16} /> Device location</dt>
              <dd>{device?.location || auth.deviceLocation || 'Not available'}</dd>
            </div>
            <div>
              <dt><RefreshCw size={16} /> Terminal heartbeat</dt>
              <dd>
                {device
                  ? `${device.isOnline ? 'Online' : 'Offline'}${device.lastSeenAt ? ` · last seen ${formatDateTime(device.lastSeenAt)}` : ''}`
                  : 'Not available'}
              </dd>
            </div>
            <div>
              <dt><RefreshCw size={16} /> Session status</dt>
              <dd>
                <StatusBadge status={getSessionStatus(session)} />
              </dd>
            </div>
          </dl>
        </article>
      </section>

      <section className="content-grid settings-rosters">
        <article className="panel settings-card">
          <div className="panel-heading">
            <div>
              <span className="eyebrow">Class rosters</span>
              <h2>Upload enrolled students</h2>
            </div>
            <StatusBadge status={parsedRosterCount > 0 ? 'ACTIVE' : 'IDLE'}>
              {parsedRosterCount} rows ready
            </StatusBadge>
          </div>

          <form className="login-form" onSubmit={handleSaveRoster}>
            <label className="field">
              <span>Course code</span>
              <div className="field__input">
                <BookOpen size={18} />
                <input
                  type="text"
                  value={rosterForm.courseCode}
                  onChange={(event) => updateRosterForm('courseCode', event.target.value.toUpperCase())}
                  placeholder="CSC401"
                  required
                />
              </div>
            </label>

            <label className="field">
              <span>Course title</span>
              <div className="field__input">
                <BookOpen size={18} />
                <input
                  type="text"
                  value={rosterForm.courseTitle}
                  onChange={(event) => updateRosterForm('courseTitle', event.target.value)}
                  placeholder="Computer Networks"
                />
              </div>
            </label>

            <label className="field">
              <span>Lecturer</span>
              <div className="field__input">
                <Users size={18} />
                <input
                  type="text"
                  value={rosterForm.lecturerId}
                  onChange={(event) => updateRosterForm('lecturerId', event.target.value)}
                  placeholder="Dr John"
                />
              </div>
            </label>

            <label className="field">
              <span>Roster CSV</span>
              <textarea
                className="roster-textarea"
                value={rosterForm.rosterCsv}
                onChange={(event) => updateRosterForm('rosterCsv', event.target.value)}
                rows={12}
                spellCheck="false"
              />
            </label>

            <p className="settings-help">
              Expected columns:
              {' '}
              <code>matricNumber,firstName,lastName,department,email,phoneNumber</code>
            </p>

            <button
              type="submit"
              className="button button--primary"
              disabled={saveRosterMutation.isPending}
            >
              <Save size={16} />
              <span>{saveRosterMutation.isPending ? 'Saving roster...' : 'Save roster'}</span>
            </button>
          </form>
        </article>

        <article className="panel settings-card">
          <div className="panel-heading">
            <div>
              <span className="eyebrow">Saved rosters</span>
              <h2>Courses in the system</h2>
            </div>
            <button
              type="button"
              className="button button--ghost"
              onClick={() => coursesQuery.refetch()}
              disabled={coursesQuery.isFetching}
            >
              <RefreshCw size={16} />
              <span>{coursesQuery.isFetching ? 'Refreshing...' : 'Refresh courses'}</span>
            </button>
          </div>

          <div className="roster-list">
            {(coursesQuery.data ?? []).length > 0 ? (
              (coursesQuery.data ?? []).map((course) => (
                <button
                  key={course.id}
                  type="button"
                  className="roster-list__item"
                  onClick={() => loadCourseIntoForm(course)}
                >
                  <div>
                    <strong>{course.code}</strong>
                    <span>{course.title || 'Title pending'}</span>
                  </div>
                  <StatusBadge status="ACTIVE">{course.enrolledCount} enrolled</StatusBadge>
                </button>
              ))
            ) : (
              <div className="public-state public-state--info">
                Save a course roster to start calculating absences and attendance percentages.
              </div>
            )}
          </div>
        </article>
      </section>

      <section className="panel danger-zone">
        <div>
          <span className="eyebrow">Danger zone</span>
          <h2>Clear saved dashboard access</h2>
          <p>
            This removes the locally stored dashboard token from the browser and returns you to the login page.
          </p>
        </div>

        <button type="button" className="button button--danger" onClick={onLogout}>
          <Trash2 size={16} />
          <span>Clear saved access</span>
        </button>
      </section>
    </main>
  );
}
